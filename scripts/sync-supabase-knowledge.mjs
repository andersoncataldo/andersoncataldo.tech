import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, '..');

const indexPath = path.join(ROOT, 'src', 'data', 'knowledgeIndex.json');
const outSqlPath = path.join(ROOT, 'supabase', 'seed_ai_knowledge_chunks.sql');

const rawIndex = JSON.parse(fs.readFileSync(indexPath, 'utf-8'));

function sqlString(val) {
  if (val === null || val === undefined) return "''";
  return `'${String(val).replace(/'/g, "''")}'`;
}

function sqlTextArray(arr) {
  if (!Array.isArray(arr) || arr.length === 0) return "'{}'::text[]";
  const escaped = arr.map((item) => sqlString(String(item))).join(', ');
  return `ARRAY[${escaped}]::text[]`;
}

function extractLocalizedFacets(facets, lang) {
  if (!facets || typeof facets !== 'object') return {};
  const result = {};
  for (const [key, val] of Object.entries(facets)) {
    if (val && typeof val === 'object' && typeof val[lang] === 'string') {
      result[key] = val[lang];
    }
  }
  return result;
}

const rows = [];

for (const chunk of rawIndex.chunks) {
  for (const lang of ['pt', 'en']) {
    const chunkId = `${chunk.id}:${lang}`;
    const category = chunk.category || 'general';
    const title = chunk.title?.[lang] || chunk.id;
    const shortAnswer = chunk.shortAnswer?.[lang] || '';
    const content = chunk.content?.[lang] || '';
    const anchor = chunk.sectionAnchor || '#sobre';
    const keywords = Array.isArray(chunk.keywords) ? chunk.keywords : [];
    const entities = Array.isArray(chunk.entities) ? chunk.entities : [];
    const facetsObj = extractLocalizedFacets(chunk.facets, lang);
    const priority = typeof chunk.priority === 'number' ? Math.round(chunk.priority) : 5;

    rows.push(
      `(${sqlString(chunkId)}, ${sqlString(lang)}, ${sqlString(category)}, ${sqlString(title)}, ${sqlString(content)}, ${sqlString(shortAnswer)}, ${sqlString(anchor)}, ${sqlTextArray(keywords)}, ${sqlTextArray(entities)}, '{}'::text[], ${sqlString(JSON.stringify(facetsObj))}::jsonb, ${priority}, now())`,
    );
  }
}

const sql = `-- =============================================================================
-- Auto-generated by scripts/sync-supabase-knowledge.mjs
-- Total localized chunks: ${rows.length} (${rawIndex.chunks.length} PT + ${rawIndex.chunks.length} EN)
-- =============================================================================

insert into public.ai_knowledge_chunks (
  chunk_id,
  lang,
  category,
  title,
  content,
  short_answer,
  anchor,
  keywords,
  entities,
  synonyms,
  facets,
  priority,
  updated_at
)
values
  ${rows.join(',\n  ')}
on conflict (chunk_id) do update
set
  lang = excluded.lang,
  category = excluded.category,
  title = excluded.title,
  content = excluded.content,
  short_answer = excluded.short_answer,
  anchor = excluded.anchor,
  keywords = excluded.keywords,
  entities = excluded.entities,
  facets = excluded.facets,
  priority = excluded.priority,
  updated_at = now();
`;

fs.writeFileSync(outSqlPath, sql, 'utf-8');
console.log(`[sync-supabase-knowledge] Generated ${rows.length} localized chunks at ${outSqlPath}`);

if (process.env.BATCH_OUT_DIR) {
  fs.mkdirSync(process.env.BATCH_OUT_DIR, { recursive: true });
  const batchSize = 12;
  let batchIdx = 1;
  for (let i = 0; i < rows.length; i += batchSize) {
    const slice = rows.slice(i, i + batchSize);
    const batchSql = `insert into public.ai_knowledge_chunks (chunk_id, lang, category, title, content, short_answer, anchor, keywords, entities, synonyms, facets, priority, updated_at) values\n${slice.join(',\n')}\non conflict (chunk_id) do update set lang = excluded.lang, category = excluded.category, title = excluded.title, content = excluded.content, short_answer = excluded.short_answer, anchor = excluded.anchor, keywords = excluded.keywords, entities = excluded.entities, facets = excluded.facets, priority = excluded.priority, updated_at = now();`;
    fs.writeFileSync(path.join(process.env.BATCH_OUT_DIR, `batch_${batchIdx}.sql`), batchSql, 'utf-8');
    batchIdx += 1;
  }
}

